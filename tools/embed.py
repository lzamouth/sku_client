#!/usr/bin/env python3
"""Embeds a binary file as a C array: embed.py <input> <output.c> <symbol>
Generates: const unsigned char <symbol>[] = {...}; const size_t <symbol>_len = N;"""
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as out:
	out.write("/* generated by tools/embed.py from %s - do not edit */\n#include <stddef.h>\n" % sys.argv[1].replace("\\", "/").split("/")[-1])
	out.write("const unsigned char %s[] = {\n" % sys.argv[3])
	for i in range(0, len(data), 24):
		out.write("\t" + ",".join("%d" % b for b in data[i:i+24]) + ",\n")
	out.write("};\nconst size_t %s_len = %d;\n" % (sys.argv[3], len(data)))
